import pandas as pd
import statsmodels.formula.api as smf

# Коммерческие данные по региональным филиалам (обезличенные для портфолио)
# target_audience — охват целевой аудитории (тыс. пациентов в регионе)
# sales_volume — фактический объем продаж препарата за период (млн руб.)
spisok_auditorii = [30, 40, 50, 70, 80]
spisok_prodazh = [4.1, 5.4, 7.1, 8.3, 10.2]

# Формируем датафрейм для анализа
data = pd.DataFrame({
    'target_audience': spisok_auditorii,
    'sales_volume': spisok_prodazh
})

# Построение парной линейной регрессии (OLS) для моделирования спроса
# Модель позволяет оценить базовый потенциал рынка и эластичность продаж к охвату аудитории
model = smf.ols('sales_volume ~ target_audience', data=data).fit()

# Бизнес-задача: Спрогнозировать объем продаж при масштабировании промо-кампании 
# и выходе на новый региональный рынок с потенциалом охвата в 60 тыс. пациентов
new_market = pd.DataFrame({'target_audience': [60]})
predicted_sales = model.predict(new_market)[0]

# Извлекаем коэффициент детерминации для оценки надежности
r_sq = model.rsquared

# --- ВЫВОД РЕЗУЛЬТАТОВ НА ЭКРАН ---
print("==================================================================")
print(f"Эконометрический прогноз продаж для нового рынка: {predicted_sales:.2f} млн руб.")
print(f"Коэффициент детерминации модели (R-squared): {r_sq:.3f}")
print("==================================================================")

# Автоматический бизнес-интерпретатор качества модели для топ-менеджмента
print("\n📋 АНАЛИТИЧЕСКОЕ ЗАКЛЮЧЕНИЕ ДЛЯ БИЗНЕСА:")

if r_sq >= 0.85:
    print(f"• Статус модели: ВЫСОКОНАДЁЖНАЯ (Зеленая зона, R² = {r_sq:.3f})")
    print(f"• Вывод: Наша модель объясняет {r_sq*100:.1f}% всей динамики объемов продаж.")
    print("  Выбранный фактор (охват целевой аудитории) является ключевым драйвером выручки.")
    print("• Рекомендация для коммерческого директора: Точность прогноза отличная.")
    print("  Данную модель можно смело использовать для долгосрочного планирования закупок,")
    print("  утверждения маркетинговых бюджетов и минимизации рисков дефектуры на складе.")

elif 0.50 <= r_sq < 0.85:
    print(f"• Статус модели: УДОВЛЕТВОРИТЕЛЬНАЯ (Желтая зона, R² = {r_sq:.3f})")
    print(f"• Вывод: Модель объясняет {r_sq*100:.1f}% изменений в продажах. Общий тренд виден,")
    print("  о can погрешность прогнозирования остается средней.")
    print("• Рекомендация для коммерческого директора: Использовать цифры осторожно.")
    print("  Для повышения точности прогноза рекомендуется расширить модель и добавить")
    print("  дополнительные рыночные факторы (например, индекс активности конкурентов).")

else:
    print(f"• Статус модели: КРИТИЧЕСКИ СЛАБАЯ (Красная зона, R² = {r_sq:.3f})")
    print(f"• Вывод: Модель объясняет менее 50% динамики. Выбранные факторы не влияют на сбыт.")
    print("• Рекомендация для коммерческого директора: Использовать данные для планирования")
    print("  категорически нельзя. Текущие расчеты эквивалентны случайному угадыванию.")
